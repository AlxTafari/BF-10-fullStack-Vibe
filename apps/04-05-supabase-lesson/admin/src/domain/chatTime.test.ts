import { describe, expect, it } from "vitest";
import { dayKey, dayLabel, formatTimeHM, listTimeLabel } from "./chatTime";

const ATHENS = "Europe/Athens";

describe("dayKey / formatTimeHM", () => {
  it("день и время — по поясу ресторана, не по поясу машины", () => {
    // 21:30 UTC в октябре летом = 00:30 следующего дня в Афинах (EEST, +3)
    expect(dayKey("2026-10-17T21:30:00+00:00", ATHENS)).toBe("2026-10-18");
    expect(formatTimeHM("2026-10-17T21:30:00+00:00", ATHENS)).toBe("00:30");
    expect(dayKey("2026-10-17T21:30:00+00:00", "UTC")).toBe("2026-10-17");
  });

  it("23:50 и 00:10 — разные дни", () => {
    expect(dayKey("2026-10-18T20:50:00+00:00", ATHENS)).toBe("2026-10-18"); // 23:50
    expect(dayKey("2026-10-18T21:10:00+00:00", ATHENS)).toBe("2026-10-19"); // 00:10
  });

  it("зимнее время: 25 октября 2026 в 04:00 часы идут назад — сутки в 25 часов, но день один", () => {
    // 00:30Z = 03:30 EEST (до перевода), 01:30Z = 03:30 EET (после перевода): обе 25 октября
    expect(dayKey("2026-10-25T00:30:00+00:00", ATHENS)).toBe("2026-10-25");
    expect(dayKey("2026-10-25T01:30:00+00:00", ATHENS)).toBe("2026-10-25");
    // 21:30Z = 23:30 EET — ещё 25-е; 22:30Z = 00:30 EET — уже 26-е
    expect(dayKey("2026-10-25T21:30:00+00:00", ATHENS)).toBe("2026-10-25");
    expect(dayKey("2026-10-25T22:30:00+00:00", ATHENS)).toBe("2026-10-26");
    // до полуночи 24-го EEST: 20:59Z = 23:59 EEST (24-е), 21:00Z = 00:00 EEST (25-е)
    expect(dayKey("2026-10-24T20:59:00+00:00", ATHENS)).toBe("2026-10-24");
    expect(dayKey("2026-10-24T21:00:00+00:00", ATHENS)).toBe("2026-10-25");
  });

  it("летнее время: 29 марта 2026 в 03:00 часы идут вперёд — день в 23 часа", () => {
    expect(dayKey("2026-03-28T22:00:00+00:00", ATHENS)).toBe("2026-03-29"); // 00:00 EET
    expect(dayKey("2026-03-29T20:59:00+00:00", ATHENS)).toBe("2026-03-29"); // 23:59 EEST
    expect(dayKey("2026-03-29T21:00:00+00:00", ATHENS)).toBe("2026-03-30"); // 00:00 EEST
  });

  it("метка с короткой дробью разбирается", () => {
    expect(formatTimeHM("2026-10-18T12:01:00.12+00:00", "UTC")).toBe("12:01");
    expect(formatTimeHM("2026-10-18T12:02:00+00:00", "UTC")).toBe("12:02");
  });
});

describe("dayLabel", () => {
  it("Сегодня / Вчера / дата", () => {
    expect(dayLabel("2026-10-18", "2026-10-18")).toBe("Сегодня");
    expect(dayLabel("2026-10-17", "2026-10-18")).toBe("Вчера");
    expect(dayLabel("2026-10-13", "2026-10-18")).toBe("13 октября");
  });

  it("«Вчера» через границу месяца, года и 29 февраля", () => {
    expect(dayLabel("2026-09-30", "2026-10-01")).toBe("Вчера");
    expect(dayLabel("2025-12-31", "2026-01-01")).toBe("Вчера");
    expect(dayLabel("2028-02-29", "2028-03-01")).toBe("Вчера");
  });

  it("другой год — с годом", () => {
    expect(dayLabel("2025-03-05", "2026-10-18")).toBe("5 марта 2025");
  });
});

describe("listTimeLabel", () => {
  const now = new Date("2026-10-18T10:00:00Z"); // 13:00 в Афинах
  it("сегодня — часы:минуты", () => {
    expect(listTimeLabel("2026-10-18T07:05:00+00:00", now, ATHENS)).toBe("10:05");
  });
  it("«сегодня» считается по поясу ресторана: 00:30 по Афинам уже сегодня, хотя в UTC было вчера", () => {
    expect(listTimeLabel("2026-10-17T21:30:00+00:00", now, ATHENS)).toBe("00:30");
  });
  it("раньше — дата, для другого года с годом", () => {
    expect(listTimeLabel("2026-10-13T10:00:00+00:00", now, ATHENS)).toBe("13.10");
    expect(listTimeLabel("2025-10-13T10:00:00+00:00", now, ATHENS)).toBe("13.10.2025");
  });
});
