// Дефолтный лагерь при онбординге, пока выбор между Первым/Вторым временно отключён.
export const NEUTRAL_CAMP_NAME = "Нейтралитет";

// Инлайн-кнопки в тг — чистый текст без CSS, единственная "стилизация" — эмодзи в подписи.
const CAMP_EMOJI: Record<string, string> = {
  "Первый лагерь": "🔥",
  "Второй лагерь": "🌙",
  [NEUTRAL_CAMP_NAME]: "⚪",
};

export function campButtonLabel(campName: string): string {
  const emoji = CAMP_EMOJI[campName];
  return emoji ? `${emoji} ${campName}` : campName;
}

// Дательный падеж для "Теперь ты примкнул к ..." — на два жёстких лагеря MVP склонение проще зашить, чем городить морфологию.
const CAMP_DATIVE: Record<string, string> = {
  "Первый лагерь": "первому лагерю",
  "Второй лагерь": "второму лагерю",
  [NEUTRAL_CAMP_NAME]: "нейтралитету",
};

export function campDativeLabel(campName: string): string {
  return CAMP_DATIVE[campName] ?? `лагерю «${campName}»`;
}

